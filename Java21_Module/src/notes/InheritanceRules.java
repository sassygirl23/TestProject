package notes;

public class InheritanceRules {

    /*
      INHERITANCE RULES
     
     * Extends
      - ginagamit para mag-inherit from parent class
     
     * Super
      - tawag sa parent constructor
      - automatic inserted kung walang explicit constructor call
     
     * Super.field
      - access parent field
     
     * Super.method()
      - call parent method
     
     * OVERRIDING
 
     * Overriding:
      - same method name
      - same parameters
      - child class gives new behavior
     
     * POLYMORPHISM
 
     * Parent reference can point to child object.
     
     * Example:
      Animal a = new Dog();
     
     * Instance methods:
      - object type ang sinusunod
     
     * Static methods:
      - reference type ang sinusunod
     
     * ABSTRACT CLASS
      - cannot instantiate directly
      - can have abstract methods
      - can have concrete methods
     */
}