package fundamentals;

public class UnaryOperator {

    public static void main(String[] args) {

        int x = 5;

        // Unary plus
        System.out.println(+x);

        // Unary minus
        System.out.println(-x);

        // Pre-increment
        System.out.println(++x);

        // Pre-decrement
        System.out.println(--x);

        boolean flag = true;

        // Logical NOT
        System.out.println(flag);


         // ++x (dagdag muna bago gamitin)

         //x++ (gamitin muna bago dagdagan)

    }
}