package fundamentals;

public class IfElse {

    public static void main(String[] args) {

        int age = 20;

        // if condition
        if (age >= 18) {

            System.out.println("Adult");

        } else {

            System.out.println("Minor");
        }

        /*
         * if statement (executes kapag true)
         * else (kapag false)
         */
    }
}