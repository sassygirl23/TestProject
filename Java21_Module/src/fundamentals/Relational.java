package fundamentals;

public class Relational {

    public static void main(String[] args) {

        int a = 10;
        int b = 20;

        System.out.println(a > b);
        System.out.println(a < b);
        System.out.println(a >= b);
        System.out.println(a <= b);
        System.out.println(a == b);
        System.out.println(a != b);

        /*
         * Relational operators will always return boolean (eme not yet sure hahaha)
         */
    }
}