package fundamentals;

public class Operator {

    public static void main(String[] args) {

        int x = 10;

        // += operator
        x += 5;
        System.out.println(x);

        // -= operator
        x -= 3;
        System.out.println(x);

        // *= operator
        x *= 2;
        System.out.println(x);

        // /= operator
        x /= 4;
        System.out.println(x);

/*
* x += 5
* shortcut ng:
* x = x + 5
*/
    }
}