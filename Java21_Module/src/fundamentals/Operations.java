package fundamentals;

public class Operations {

    public static void main(String[] args) {

        int a = 10;
        int b = 3;

        // Addition
        System.out.println(a + b);

        // Subtraction
        System.out.println(a - b);

        // Multiplication
        System.out.println(a * b);

        // Division
        System.out.println(a / b);

        // Modulus (remainder) 
        System.out.println(a % b);

        /*
         * int / int = int
         * kaya 10 / 3 = 3
         */
    }
}